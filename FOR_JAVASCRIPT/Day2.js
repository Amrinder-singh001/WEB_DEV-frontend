// About All Primitive Data Types 
// What are Primitive Data Types?

// Primitive data types are the basic types of data in JavaScript. They store a single value and are immutable (their values cannot be changed directly).

// To check the data type of your data by (typeof) keyword.
// There are 7 Primitive Data Types:

// 1. String
// Stores text or characters.
// Written inside single (' '), double (" "), or backtick (` `) quotes.

Example:
"Hello"
'JavaScript'

// 2. Number
// Stores integers and decimal numbers.
// Positive and negative numbers are allowed.

Example:
10
25.5
-100

// 3. Boolean
// Stores only two values:
Example:
true
false
// Used for decision making.

// 4. Undefined
// A variable has been declared but no value has been assigned.
Example:
let x;

// 5. Null
// Represents an intentionally empty or unknown value.
// Value is assigned manually.
Example:
let user = null;

// 6. BigInt
// Used to store very large integers beyond the safe Number limit.
// Created by adding n at the end of the number.
Example:
12345678901234567890n

// 7. Symbol
// Used to create unique values.
// Mostly used for unique object property keys.