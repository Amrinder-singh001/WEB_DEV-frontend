// JavaScript Variables – Easy Short Notes
// What is a Variable?

// A variable is a container (or box) used to store data.

// Example:

// name = "Amrinder"
// age = 20
// Types of Variables
// 1. let
// Used when the value can change.
// Can be updated later.
// Most commonly used.

// Example:
// let age = 20
// age = 21

// 2. const
// Used when the value should not change.
// Must be assigned a value when created.
// Cannot be updated later.

// Example:
// const country = "India"

// 3. var
// Old way of creating variables.
// Can be updated and redeclared.
// Not recommended in modern JavaScript.
// Variable Naming Rules

// Correct:

// firstName
// age
// _score
// $price
// marks1

// Incorrect:

// 1name
// first-name
// let
// const
// Data That Variables Can Store
// String → Text (e.g., "Hello")
// Number → 10, 25.5
// Boolean → true, false
// Null → Empty value
// Undefined → Value not assigned
// Difference Between let, const, and var

// let

// Value can change: Yes
// Redeclare: No
// Recommended: Yes

// const

// Value can change: No
// Redeclare: No
// Recommended: Yes

// var

// Value can change: Yes
// Redeclare: Yes
// Recommended: No

Example

let name = "amrinder singh";
console.log(name);  

const country = india;
console.log(country);

var age = 19;
age = 21;
console.log(age);

